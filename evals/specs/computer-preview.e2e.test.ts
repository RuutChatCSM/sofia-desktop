import { spawn } from "node:child_process";
import { mkdir, mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { expect, onTestFinished } from "vitest";
import { connect, debuggerUrlFor, evaluate, listTargets, captureScreenshot } from "@sofia/cdp";
import { needs, test } from "@sofia/testkit";
import { createServer } from "../../apps/app/node_modules/vite/dist/node/index.js";

const appRoot = resolve(import.meta.dirname, "../../apps/app");
const chrome = process.env.SOFIA_EVAL_CHROME_BINARY || "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome";
const sleep = (ms: number) => new Promise((resolveSleep) => setTimeout(resolveSleep, ms));

test("computer preview renders, hides durably, restores, moves, and disposes media on target/run/session changes", async ({ evidence }) => {
  needs({ optIn: ["SOFIA_EVAL_E2E_TESTS"], placement: "local" });
  const profile = await mkdtemp(join(tmpdir(), "sofia-preview-eval-"));
  onTestFinished(() => rm(profile, { recursive: true, force: true }));
  const vite = await createServer({ root: appRoot, server: { host: "127.0.0.1", port: 0, strictPort: false } });
  onTestFinished(() => vite.close());
  await vite.listen();
  const address = vite.httpServer?.address();
  if (!address || typeof address === "string") throw new Error("Preview fixture server did not bind");
  const url = `http://127.0.0.1:${address.port}/tests/fixtures/computer-preview.html`;
  const child = spawn(chrome, ["--headless=new", "--remote-debugging-port=0", `--user-data-dir=${profile}`, "--no-first-run", "--no-default-browser-check", "--window-size=1000,800", url], { stdio: "ignore" });
  onTestFinished(async () => { child.kill(); await new Promise<void>((done) => child.once("exit", () => done())); });
  let port = "";
  for (let attempt = 0; attempt < 100 && !port; attempt++) {
    try { port = (await readFile(join(profile, "DevToolsActivePort"), "utf8")).split("\n")[0]; } catch { await sleep(100); }
  }
  if (!port) throw new Error("Isolated Chrome did not expose its fixture debugger");
  const base = `http://127.0.0.1:${port}`;
  const target = (await listTargets(base)).find((entry) => entry.url === url);
  if (!target) throw new Error("Preview fixture target missing");
  const client = await connect(debuggerUrlFor(base, target));
  onTestFinished(() => client.close());
  const wait = async (expression: string) => {
    for (let attempt = 0; attempt < 100; attempt++) {
      if (await evaluate(client, expression)) return;
      await sleep(100);
    }
    const state = await evaluate(client, "JSON.stringify({stats:{stopped:window.previewFixture?.stats().stopped,streams:window.previewFixture?.stats().streams},text:document.body.innerText})");
    throw new Error(`Preview condition timed out: ${expression}; ${state}`);
  };
  const click = (label: string) => evaluate(client, `document.querySelector('button[aria-label="${label}"]').click()`);
  await wait("!!document.querySelector('[data-testid=computer-peek] video')?.srcObject");
  expect(await evaluate(client, `(() => {const p=document.querySelector('[data-testid=computer-peek]');const r=p.getBoundingClientRect();const o=document.querySelector('[data-computer-preview-obstacle]').getBoundingClientRect();return {width:r.width,height:r.height,clear:r.right<=o.left-12||r.top>=o.bottom+12,session:p.dataset.previewSession}})()`)).toEqual({ width: 200, height: 150, clear: true, session: "session-a" });
  const changeSize = (value: number) => evaluate(client, `(()=>{const input=document.querySelector('select[aria-label="Computer preview size"]');input.value='${value}';input.dispatchEvent(new Event('change',{bubbles:true}))})()`);
  await changeSize(400);
  await wait("document.querySelector('[data-testid=computer-peek]').getBoundingClientRect().width===400");
  expect(await evaluate(client, "document.querySelector('[data-testid=computer-peek]').getBoundingClientRect().height")).toBe(300);
  expect(await evaluate(client, "previewFixture.stats().streams")).toBe(1);
  await changeSize(200);
  await wait("document.querySelector('[data-testid=computer-peek]').getBoundingClientRect().width===200");
  await click("Open Fixture");
  expect(await evaluate(client, "previewFixture.stats().calls.some(c=>c.command==='openComputerUsePreview'&&c.args[0].sessionId==='session-a'&&c.args[1].windowNumber===30)")).toBe(true);
  await click("Hide computer preview");
  await wait("!document.querySelector('[data-testid=computer-peek]') && previewFixture.stats().stopped===1");
  expect(await evaluate(client, "JSON.parse(localStorage.getItem('sofia:computer-preview:v1')).state.hiddenSessions['session-a']")).toBe(true);
  await evaluate(client, "previewFixture.switchSession()");
  await wait("document.querySelector('[data-preview-session=session-b]') && previewFixture.stats().streams===2");
  await evaluate(client, "previewFixture.switchSession()");
  await wait("!!document.querySelector('[data-testid=computer-peek-restore]') && previewFixture.stats().stopped===2");
  await click("Show computer preview");
  await wait("previewFixture.stats().streams===3 && !!document.querySelector('video')?.srcObject");
  await evaluate(client, "previewFixture.changeTarget()");
  await wait("previewFixture.stats().streams===4 && previewFixture.stats().stopped===3");
  await evaluate(client, "previewFixture.finish()");
  await wait("!document.querySelector('[data-testid=computer-peek]') && previewFixture.stats().stopped===4");
  await evaluate(client, "previewFixture.hold();previewFixture.start()");
  await wait("previewFixture.stats().streams===5");
  await click("Hide all computer previews");
  await evaluate(client, "previewFixture.release()");
  await wait("previewFixture.stats().stopped===5 && !document.querySelector('[data-testid=computer-peek]')");
  expect(await evaluate(client, "JSON.parse(localStorage.getItem('sofia:computer-preview:v1')).state.alwaysHide")).toBe(true);
  await click("Show computer preview");
  await wait("previewFixture.stats().streams===6 && !!document.querySelector('video')?.srcObject");
  // Drag with browser input, then verify the product's viewport clamp.
  const box = await evaluate(client, `(() => {const r=document.querySelector('[data-testid=computer-peek]').getBoundingClientRect();return {x:r.x+50,y:r.y+50}})()`);
  if (!box || typeof box !== "object" || !("x" in box) || !("y" in box)) throw new Error("Preview drag bounds missing");
  await client.send("Input.dispatchMouseEvent", { type: "mousePressed", x: box.x, y: box.y, button: "left", clickCount: 1 });
  await client.send("Input.dispatchMouseEvent", { type: "mouseMoved", x: 980, y: 740, button: "left", buttons: 1 });
  await client.send("Input.dispatchMouseEvent", { type: "mouseReleased", x: 980, y: 740, button: "left", clickCount: 1 });
  await wait("(()=>{const r=document.querySelector('[data-testid=computer-peek]').getBoundingClientRect();return r.x>600&&r.y>350&&r.right<=876&&r.bottom<=576})()");
  await evaluate(client, "document.querySelector('button[aria-label=\"Hide computer preview\"]').focus()");
  await wait("getComputedStyle(document.querySelector('[aria-label=\"Computer preview controls\"]')).opacity==='1'");
  expect(await evaluate(client, "document.querySelector('[aria-label=\"Computer preview controls\"]').getBoundingClientRect().height")).toBe(34);
  const png = await captureScreenshot(client);
  await mkdir(evidence.dir, { recursive: true });
  await writeFile(join(evidence.dir, "computer-preview.png"), png);
  await click("Hide all computer previews");
  await wait("previewFixture.stats().stopped===6");
  const previousPage = await evaluate(client, "previewFixture.pageId");
  await client.send("Page.reload");
  await wait(`!!window.previewFixture && window.previewFixture.pageId !== ${JSON.stringify(previousPage)}`);
  await wait("!!document.querySelector('[data-testid=computer-peek-restore]')");
  expect(await evaluate(client, "previewFixture.stats().streams")).toBe(0);
  expect(await evaluate(client, "JSON.parse(localStorage.getItem('sofia:computer-preview:v1')).state.maximumDimension")).toBe(200);
  await evaluate(client, "previewFixture.deny()");
  await click("Show computer preview");
  await wait("previewFixture.stats().streams===1 && !!document.querySelector('[data-testid=computer-peek] img')");
  expect(await evaluate(client, "previewFixture.stats().fallbacks")).toBe(0);
  expect(await evaluate(client, "document.querySelector('video').srcObject")).toBeNull();
  await changeSize(400);
  await evaluate(client, "document.querySelector('main').style.width='320px';document.querySelector('main').style.height='400px'");
  await wait("document.querySelector('[data-testid=computer-peek]').getBoundingClientRect().width===272");
  expect(await evaluate(client, `(()=>{const frame=document.querySelector('[data-testid=computer-peek]').getBoundingClientRect();const host=document.querySelector('main').getBoundingClientRect();return {height:frame.height,fits:frame.left>=host.left&&frame.top>=host.top&&frame.right<=host.right&&frame.bottom<=host.bottom}})()`)).toEqual({height:204,fits:true});
  await evaluate(client, "previewFixture.start()");
  await wait("document.querySelector('[data-completion-stage=active]')!==null");
  const readsBeforeCompletion = await evaluate(client, "previewFixture.stats().calls.filter(c=>c.command==='getComputerUsePreview').length");
  await evaluate(client, "previewFixture.complete()");
  await wait("document.querySelector('[data-completion-stage=icon]')!==null");
  await wait("document.querySelector('[data-completion-stage=full]')!==null");
  await wait("document.querySelector('[data-completion-stage=mini]')!==null");
  expect(await evaluate(client, "previewFixture.stats().calls.filter(c=>c.command==='getComputerUsePreview').length")).toBe(readsBeforeCompletion);
  await writeFile(join(evidence.dir, "computer-preview-completed.png"), await captureScreenshot(client));
  await sleep(28_000);
  await wait("!document.querySelector('[data-testid=computer-peek]')");
  evidence.recordAssertionEvidence("Successful completion lifecycle", "Successful completion retains the preview, shows icon/full/mini stages in order, stops native polling, and expires after 30 seconds. Active controls are overlaid inside the image.", true);
  evidence.recordAssertionEvidence("Rendered computer preview lifecycle", "The actual React panel retains 200×150 aspect, avoids a composer obstacle, opens its scoped target, persists hide choices with restore, stops tracks on session/target/completion and on a delayed permission result, and clamps a browser-driven drag. Capture uses only an isolated generated canvas; native OS capture is not exercised.", true);
  evidence.recordAssertionEvidence("Durable hiding and capture denial", "Reload preserves hide-all without starting media. Restore clears hiding; capture denial retains the scoped JPEG and never opens an unscoped display-media picker.", true);
  evidence.recordAssertionEvidence("Adjustable preview sizing", "The initial 200×150 preview enlarges to 400×300 and shrinks to 200×150 with its size control; resizing does not restart capture, the chosen size survives reload, and a 320px host constrains a Large preview to 272×204 inside its bounds.", true);
});
